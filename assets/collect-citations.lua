-- Pre-render script: collects every citation key used in the slide decks and
-- writes them as `nocite` to _citations.yml, which references.qmd loads via
-- `metadata-files`. This way the book's References chapter lists the
-- references of both presentations (the book chapters only embed the slides
-- and cite nothing themselves).
--
-- Why not a Lua filter? Quarto books hide each page's #refs div after
-- rendering and rebuild the References page from the citations found in the
-- book's HTML plus the `nocite` *YAML metadata* of the documents. A `nocite`
-- set by a filter at Pandoc runtime is invisible to that step.

local decks = {
  "1.0-foundations-of-fairness-slides.qmd",
  "2.0-research-findings-slides.qmd",
}

local seen, keys = {}, {}
for _, path in ipairs(decks) do
  local fh = io.open(path, "r")
  if fh then
    local text = fh:read("a")
    fh:close()
    -- citation keys: "@key" not preceded by a word character (skips e-mails)
    for key in ("\n" .. text):gmatch("[^%w_]@([%w_][%w_:%-%.]*[%w_])") do
      if not seen[key] then
        seen[key] = true
        table.insert(keys, "@" .. key)
      end
    end
  else
    io.stderr:write("collect-citations.lua: could not read " .. path .. "\n")
  end
end

local out = assert(io.open("_citations.yml", "w"))
out:write("# Generated by assets/collect-citations.lua -- do not edit.\n")
out:write('nocite: "' .. table.concat(keys, ", ") .. '"\n')
out:close()
